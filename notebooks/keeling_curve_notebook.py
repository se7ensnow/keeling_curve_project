"""## 7. Polynomial and Seasonal Models

$$
CO_2(t) = \sum_{j=0}^{d} a_j t^j +
\sum_{k=1}^{H}
\left[
b_k \sin(2\pi kt) +
c_k \cos(2\pi kt)
\right]
$$


"""

class PolynomialSeasonalModel:
    def __init__(self, degree=2, harmonics=1):
        self.degree = degree
        self.harmonics = harmonics
        self.coef_ = None

    def _features(self, t):
        t = np.atleast_1d(np.asarray(t, dtype=float))
        x = t / 10

        features = [x**d for d in range(self.degree + 1)]

        for k in range(1, self.harmonics + 1):
            features.append(np.sin(2 * np.pi * k * t))
            features.append(np.cos(2 * np.pi * k * t))

        return np.column_stack(features)

    def fit(self, t, y):
        X = self._features(t)
        self.coef_ = np.linalg.lstsq(
            X, np.asarray(y), rcond=None
        )[0]
        return self

    def predict(self, t):
        return self._features(t) @ self.coef_

