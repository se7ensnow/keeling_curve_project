"""## 5. Linear Baseline

$$
CO_2(t) = a + bt
$$

"""

class LinearModel:
    def __init__(self):
        self.intercept_ = None
        self.slope_ = None

    def fit(self, t, y):
        t = np.asarray(t)
        y = np.asarray(y)

        X = np.column_stack([
            np.ones(len(t)),
            t
        ])

        self.intercept_, self.slope_ = np.linalg.lstsq(
            X, y, rcond=None
        )[0]

        return self

    def predict(self, t):
        t = np.asarray(t)
        return self.intercept_ + self.slope_ * t

