"""
## 8. Non-linear Exponential Model

$$
CO_2(t) = c_0 + ae^{rt} +
\sum_{k=1}^{H}
\left[
b_k \sin(2\pi kt) +
c_k \cos(2\pi kt)
\right]
$$
"""

from scipy.optimize import minimize_scalar


class ExponentialSeasonalModel:
    def __init__(self, harmonics=4, rate_bounds=(0.005, 0.1)):
        self.harmonics = harmonics
        self.rate_bounds = rate_bounds
        self.rate_ = None
        self.coef_ = None

    def _features(self, t, rate):
        t = np.atleast_1d(np.asarray(t, dtype=float))

        features = [
            np.ones(len(t)),
            np.expm1(rate * t)
        ]

        for k in range(1, self.harmonics + 1):
            features.append(np.sin(2 * np.pi * k * t))
            features.append(np.cos(2 * np.pi * k * t))

        return np.column_stack(features)

    def fit(self, t, y):
        t = np.asarray(t, dtype=float)
        y = np.asarray(y, dtype=float)

        def objective(rate):
            X = self._features(t, rate)
            coef = np.linalg.lstsq(X, y, rcond=None)[0]
            residuals = y - X @ coef
            return np.sum(residuals**2)

        result = minimize_scalar(
            objective,
            bounds=self.rate_bounds,
            method="bounded"
        )

        self.rate_ = result.x

        X = self._features(t, self.rate_)
        self.coef_ = np.linalg.lstsq(
            X, y, rcond=None
        )[0]

        return self

    def predict(self, t):
        X = self._features(t, self.rate_)
        return X @ self.coef_

    def trend(self, t):
        t = np.asarray(t, dtype=float)
        return (
            self.coef_[0]
            + self.coef_[1] * np.expm1(self.rate_ * t)
        )

