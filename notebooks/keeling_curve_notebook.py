def load_co2_data(path: str | Path) -> pd.DataFrame:
    df = pd.read_csv(
        path,
        comment="#",
        skipinitialspace=True
    )

    df["date"] = pd.to_datetime(
        df[["year", "month"]].assign(day=1)
    )

    df["t"] = (
        (df["year"] - 1958)
        + (df["month"] - 3) / 12
    )

    # Historical Scripps measurements
    df["is_scripps"] = df["date"] <= "1974-04-01"

    # Interpolated NOAA monthly values
    df["is_interpolated"] = (
        ~df["is_scripps"]
        & (df["sdev"] < 0)
    )

    # Months affected by the Maunakea station switch
    df["is_maunakea"] = df["date"].between(
        "2022-12-01",
        "2023-07-01"
    )

    return df

